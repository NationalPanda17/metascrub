// Parses metadata-laden fixtures, strips them, and verifies nothing sensitive survives.
import fs from 'fs';
import { execFileSync } from 'child_process';
import { analyze, strip } from '../js/parsers.js';
import { strangerSummary } from '../js/summary.js';
import { writeZip, readZip } from '../js/zip.js';

const dir = new URL('./fixtures/', import.meta.url).pathname;
if (!fs.existsSync(dir + 'test.jpg')) execFileSync('python3', [new URL('./make_fixtures.py', import.meta.url).pathname, dir], { stdio: 'inherit' });

let failed = 0;
const ok = (cond, msg) => { console.log(`${cond ? 'PASS' : 'FAIL'} ${msg}`); if (!cond) failed++; };

for (const f of ['test.jpg', 'test.png', 'test.webp']) {
  const b = new Uint8Array(fs.readFileSync(dir + f));
  const r = await analyze(b);
  ok(r.gps && Math.abs(r.gps.lat - 38.804833) < 1e-4 && r.gps.lon < 0, `${f}: GPS decoded (${r.gps?.lat}, ${r.gps?.lon})`);
  ok(r.counts.identity >= 2, `${f}: identity fields found (artist, serial)`);
  if (f === 'test.jpg') ok(strangerSummary(r).every((s) => typeof s.label === 'string'), `${f}: summary findings have text labels`);
  if (f === 'test.jpg') ok(r.hiddenBytes > 0, `${f}: trailing hidden data detected`);
  const clean = await strip(b, r.format, { keepOrientation: true, keepICC: true });
  const r2 = await analyze(clean);
  const left = r2.groups.flatMap((g) => g.entries).filter((e) => e.name !== 'Orientation');
  ok(left.length === 0 && !r2.gps && !r2.hiddenBytes, `${f}: clean copy has no metadata (${b.length} → ${clean.length} bytes)`);
  if (f === 'test.jpg') ok(r2.orientation === 6, `${f}: orientation preserved`);
}
// iPhone-style HEIC (generated by make_heic.py)
if (!fs.existsSync(dir + 'iphone.heic')) execFileSync('python3', [new URL('./make_heic.py', import.meta.url).pathname, dir], { stdio: 'inherit' });
for (const f of ['iphone.heic', 'iphone_idat.heic', 'iloc_v0.heic']) {
  const b = new Uint8Array(fs.readFileSync(dir + f));
  const r = await analyze(b);
  ok(r.format === 'heif' && r.gps && r.gps.lon < -77 && r.counts.device >= 3, `${f}: EXIF + GPS read from HEIC (${r.gps?.lat}, ${r.gps?.lon})`);
  ok(r.groups.some((g) => /XMP/.test(g.name)), `${f}: XMP item read`);
  const clean = await strip(b, r.format, { keepOrientation: true });
  const r2 = await analyze(clean);
  const left = r2.groups.flatMap((g) => g.entries).filter((e) => e.name !== 'Orientation' && !/irot/.test(e.name));
  ok(clean.length === b.length && left.length === 0 && !r2.gps, `${f}: cleaned in place, same size, nothing sensitive left`);
}
const plain = new Uint8Array(fs.readFileSync(dir + 'plain.jpg'));
ok((await analyze(plain)).total === 0, 'plain.jpg: no false positives');
ok((await strip(plain, 'jpeg')).length === plain.length, 'plain.jpg: stripping is a no-op');
ok(strangerSummary(await analyze(plain)).length === 0, 'plain.jpg: stranger summary is empty');

// Office + PDF (generated by make_docs.py; needs python-docx, openpyxl, python-pptx, reportlab, pypdf)
const sensitive = (r) => r.groups.flatMap((g) => g.entries).filter((e) => (e.category === 'identity' || e.category === 'location') && !/^author$/i.test(String(e.value).trim()));
try {
  if (!fs.existsSync(dir + 'memo.pdf')) execFileSync('python3', [new URL('./make_docs.py', import.meta.url).pathname, dir], { stdio: 'inherit' });
  for (const f of ['report.docx', 'budget.xlsx', 'deck.pptx', 'memo.pdf']) {
    const b = new Uint8Array(fs.readFileSync(dir + f));
    const r = await analyze(b);
    ok(sensitive(r).length >= 1, `${f}: personal fields found (${sensitive(r).map((e) => e.value).slice(0, 3).join(', ')})`);
    const clean = await strip(b, r.format, { anonymize: true });
    const r2 = await analyze(clean);
    ok(sensitive(r2).length === 0 && !r2.gps, `${f}: cleaned, no names/places left`);
    if (f === 'memo.pdf') ok(clean.length === b.length, 'memo.pdf: blanked in place (same size, every revision)');
  }
  const doc = await analyze(new Uint8Array(fs.readFileSync(dir + 'report.docx')));
  ok(doc.gps && strangerSummary(doc).some((s) => /photo inside/.test(s.text)), 'report.docx: GPS found inside an embedded photo');
} catch (e) { console.log(`- skipped Office/PDF checks (${e.message.split('\n')[0]})`); }

// Video (generated with ffmpeg if available)
try {
  const mk = (name, args) => { if (!fs.existsSync(dir + name)) execFileSync('ffmpeg', ['-v', 'error', '-y', '-f', 'lavfi', '-i', 'testsrc=size=160x120:rate=10', '-t', '1', '-c:v', 'mpeg4', ...args, dir + name]); };
  mk('iphone.mov', ['-movflags', 'use_metadata_tags', '-metadata', 'com.apple.quicktime.location.ISO6709=+38.8042-077.0472+014.200/', '-metadata', 'com.apple.quicktime.make=Apple', '-metadata', 'com.apple.quicktime.model=iPhone 16 Pro']);
  mk('android.mp4', ['-metadata', 'location=+38.8042-077.0472+014.200/', '-metadata', 'creation_time=2026-11-02T09:14:55Z']);
  mk('camera.mov', ['-metadata', 'location=+38.8042-077.0472/', '-metadata', 'make=Samsung', '-metadata', 'model=Galaxy S25']);
  for (const f of ['iphone.mov', 'android.mp4', 'camera.mov']) {
    const b = new Uint8Array(fs.readFileSync(dir + f));
    const r = await analyze(b);
    ok(r.isVideo && r.gps && r.gps.lon < -77, `${f}: video GPS read (${r.gps?.lat}, ${r.gps?.lon})`);
    const clean = await strip(b, r.format);
    const r2 = await analyze(clean);
    ok(clean.length === b.length && !r2.gps && r2.total === 0, `${f}: cleaned in place, nothing left`);
    fs.writeFileSync(dir + 'clean_' + f, clean);
    execFileSync('ffmpeg', ['-v', 'error', '-i', dir + 'clean_' + f, '-f', 'null', '-']);
    ok(true, `${f}: cleaned video still decodes`);
  }
} catch (e) { console.log(`- skipped video checks (${e.message.split('\n')[0]})`); }

// ZIP round trip
const zfiles = [{ name: 'a.txt', data: new TextEncoder().encode('hello '.repeat(100)) }, { name: 'b.bin', data: new Uint8Array(500).map((_, i) => i & 255), store: true }];
const zbytes = await writeZip(zfiles);
const back = await Promise.all(readZip(zbytes).map((e) => e.read()));
ok(back[0].length === 600 && back[1][499] === 499 % 256, 'zip: write + read round trip');

if (failed) { console.error(`\n${failed} check(s) failed`); process.exit(1); }
console.log('\nAll metadata checks passed');
